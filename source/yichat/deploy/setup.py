"""Existing-installation upgrade. Run with sudo after an online DB/config backup.
Only YiChat services are stopped/restarted; the main site reload is a separate step.
Secrets are generated by provision_archive, never printed or committed.
"""
import json,os,shlex,subprocess,sys,time,shutil,sqlite3
from pathlib import Path
import yaml


def read_env(path):
    result={}
    for line in path.read_text().splitlines():
        if not line.strip() or line.lstrip().startswith('#') or '=' not in line:continue
        key,value=line.split('=',1);parts=shlex.split(value)
        result[key]=parts[0] if len(parts)==1 else value
    return result


def write_env(path,values):
    path.write_text(''.join(key+'='+shlex.quote(str(value))+'\n' for key,value in values.items()));path.chmod(0o600)


def main():
    if os.geteuid()!=0:raise SystemExit('Run with sudo')
    base=Path(__file__).resolve().parents[1];cfg=Path('/etc/yichat');envfile=cfg/'yichat.env';config=cfg/'synapse.yaml'
    if not envfile.exists() or not config.exists():raise SystemExit('Existing YiChat/Synapse configuration required. Do not fabricate keys; restore the existing installation first.')
    sys.path.insert(0,str(base));sys.path.insert(0,str(base.parent));sys.path.insert(0,str(base/'deploy'))
    from provision_archive import provision
    dsns=provision()
    backup=base.parent/'backups'/('yichat-config-v2-'+time.strftime('%Y%m%d-%H%M%S'));backup.mkdir(mode=0o700,parents=True)
    for p in (envfile,config):shutil.copy2(p,backup/p.name)
    values=read_env(envfile)
    for key in ('YICHAT_FRONTEND_DIST','YICHAT_MAX_FILE_BYTES','YICHAT_MESSAGES_PER_MINUTE'):values.pop(key,None)
    values.update(YICHAT_ARCHIVE_READER_DSN=dsns['read'],YICHAT_ARCHIVE_INGEST_DSN=dsns['ingest'],YICHAT_ARCHIVE_PATH='/var/lib/yichat/archives',YICHAT_UPLOAD_RATE='500000')
    # Preserve the existing explicit funds setting and official-wallet configuration.
    write_env(envfile,values);write_env(cfg/'archive-worker.env',{'YICHAT_ARCHIVE_SEALER_DSN':dsns['seal'],'YICHAT_ARCHIVE_CLEANUP_DSN':dsns['cleanup']})
    os.environ.update(values)
    subprocess.run(['systemctl','stop','yichat.service'],check=True)
    subprocess.run(['systemctl','stop','yichat-archive.service'],check=False,stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL)
    from backend.config import Settings
    from backend.db import migrate,connect,transaction
    from backend import policy,archive
    from backend.funds import Funds
    from backend.assets import migrate as migrate_assets
    s=Settings()
    with connect(s.db) as previous:
        legacy=previous.execute('SELECT max(version) FROM yc_migrations').fetchone()[0]<2
    migrate(s);policy.migrate_identities(s);Funds(s).migrate();migrate_assets(s)
    s.archive_path.mkdir(parents=True,exist_ok=True,mode=0o700)
    with connect(s.db) as c:files=c.execute('SELECT f.*,i.mxid FROM files f JOIN identities i ON i.subject=f.uploader').fetchall()
    for row in files:
        target=s.objects/row['id']
        if target.is_file():
            digest,size=archive.file_digest(target)
            if size!=row['bytes']:raise RuntimeError('Legacy attachment size mismatch; do not seal or clean')
            with transaction(s.db) as c:c.execute('INSERT OR IGNORE INTO file_hashes VALUES(?,?)',(row['id'],digest))
            archive.record_attachment(s.archive_ingest,row['id'],row['room'],row['mxid'],int(row['completed']*1000),size,digest)
            if legacy:
                with archive.connect(s.archive_ingest) as c:
                    c.execute('INSERT INTO archive_gaps VALUES(%s,%s,%s,%s) ON CONFLICT DO NOTHING',(row['id'],row['room'],archive.utcday(int(row['completed']*1000)),'Legacy attachment accepted-event association unknown; manual evidence migration required'))
        else:
            with archive.connect(s.archive_ingest) as c:
                c.execute('INSERT INTO archive_gaps VALUES(%s,%s,%s,%s) ON CONFLICT DO NOTHING',(row['id'],row['room'],archive.utcday(int(row['completed']*1000)),'Legacy file missing; original-byte SHA-256 unavailable'))
    data=yaml.safe_load(config.read_text())
    data.update(enable_registration=False,enable_registration_without_verification=False,allow_guest_access=False,enable_media_repo=False,federation_domain_whitelist=[],trusted_key_servers=[],url_preview_enabled=False,retention={'enabled':False},redaction_retention_period=None,forgotten_room_retention_period=None)
    data['rc_message']={'per_second':10,'burst_count':10}
    data['modules']=[m for m in data.get('modules',[]) if m['module']!='backend.synapse_module.YiChatModule']+[{'module':'backend.synapse_module.YiChatModule','config':{}}]
    config.write_text(yaml.safe_dump(data));config.chmod(0o600)
    for unit in ('yichat.service','yichat-synapse.service','yichat-archive.service'):
        shutil.copy2(base/'deploy'/unit,Path('/etc/systemd/system')/unit)
    main_env=Path('/etc/systemd/system/website.service.d/yichat-social.conf');main_env.parent.mkdir(exist_ok=True)
    main_env.write_text('[Service]\nEnvironment=YICHAT_RATE_DB='+str(s.db)+'\n')
    subprocess.run(['systemctl','daemon-reload'],check=True)
    subprocess.run(['systemctl','restart','yichat-synapse.service'],check=True)
    subprocess.run(['systemctl','enable','--now','yichat.service','yichat-archive.service'],check=True)
    print('YiChat v2 migration/configuration applied. Reload website.service to enable account/OIDC changes. No real funds used.')


if __name__=='__main__':main()
